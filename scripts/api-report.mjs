/**
 * Write the public API report: every declaration file reachable from an export
 * entry in the built `dist/`, printed without comments, into
 * `api/foundation.api.md`. With `--check` it fails when the committed report is
 * out of date instead.
 *
 * @author      Ben Carey <bdmc@sinemacula.co.uk>
 * @copyright   2026 Sine Macula Limited
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, posix } from 'node:path';

import ts from 'typescript';

const PACKAGE = '@sinemacula/foundation';
const REPORT = 'api/foundation.api.md';

const printer = ts.createPrinter({ removeComments: true });
const manifest = JSON.parse(readFileSync('package.json', 'utf8'));

/** The relative module specifiers a declaration node imports or re-exports. */
function relativeSpecifiers(node) {
    const specifier = ts.isImportTypeNode(node) ? node.argument.literal : node.moduleSpecifier;
    const specifiers =
        specifier !== undefined && ts.isStringLiteral(specifier) && specifier.text.startsWith('.')
            ? [specifier.text]
            : [];

    ts.forEachChild(node, child => {
        specifiers.push(...relativeSpecifiers(child));
    });

    return specifiers;
}

/**
 * Parse every declaration file reachable from the export entries through
 * relative imports and triple-slash path references, keyed by `dist`-relative
 * path, failing on a reference that resolves to no file.
 */
function reachableDeclarations(entries) {
    const files = new Map();
    const pending = [...entries];

    while (pending.length > 0) {
        const path = pending.pop();

        if (files.has(path)) {
            continue;
        }

        const source = ts.createSourceFile(path, readFileSync(join('dist', path), 'utf8'), ts.ScriptTarget.Latest);

        files.set(path, source);

        const references = [
            ...relativeSpecifiers(source).map(specifier => specifier.replace(/\.js$/, '.d.ts')),
            ...source.referencedFiles.map(({ fileName }) => fileName),
        ];

        for (const reference of references) {
            const target = posix.join(posix.dirname(path), reference);

            if (!existsSync(join('dist', target))) {
                console.error(`dist/${path} references ${reference}, which resolves to no declaration file.`);
                process.exit(1);
            }

            pending.push(target);
        }
    }

    return files;
}

const subpaths = new Map(
    Object.entries(manifest.exports).map(([key, { types }]) => [
        types.replace(/^\.\/dist\//, ''),
        `${PACKAGE}/${key.slice(2)}`,
    ]),
);
const declarations = reachableDeclarations(subpaths.keys());
const sections = [...declarations.keys()].sort().map(path => {
    const exposure = subpaths.has(path) ? `Exported as \`${subpaths.get(path)}\`.` : 'Internal.';

    return `## dist/${path}\n\n${exposure}\n\n\`\`\`ts\n${printer.printFile(declarations.get(path))}\`\`\`\n`;
});
const report = [
    '# Public API report\n',
    'Generated by `npm run api:report` from the built declarations. Review every change to this file.\n',
    ...sections,
].join('\n');

if (process.argv.includes('--check')) {
    if (!existsSync(REPORT) || readFileSync(REPORT, 'utf8') !== report) {
        console.error(`${REPORT} is out of date; run npm run api:report and review the diff.`);
        process.exit(1);
    }
} else {
    mkdirSync(dirname(REPORT), { recursive: true });
    writeFileSync(REPORT, report);
}
